CREATE TABLE HUESPEDES (
   ID_HUESPED        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
   NOMBRE            VARCHAR2(50) NOT NULL,
   APELLIDO_PATERNO  VARCHAR2(50) NOT NULL,
   APELLIDO_MATERNO  VARCHAR2(50) NOT NULL,
   EMAIL             VARCHAR2(100) NOT NULL,
   TELEFONO          VARCHAR2(10) NOT NULL,
   DOCUMENTO         VARCHAR2(30) NOT NULL,
   NACIONALIDAD      VARCHAR2(30) NOT NULL,
   ESTADO_REGISTRO   VARCHAR2(30) NOT NULL,
   CONSTRAINT PK_ID_HUESPED PRIMARY KEY ( ID_HUESPED ),
   CONSTRAINT CHECK_DOCUMENTO
      CHECK ( DOCUMENTO IN ( 'CREDENCIAL',
                             'PASAPORTE',
                             'CARTILLA_MILITAR',
                             'CURP' ) ),
   CONSTRAINT HUESPED_TELEFONO_CHK CHECK ( REGEXP_LIKE ( TELEFONO,
                                                         '^[0-9]{10}$' ) ),
   CONSTRAINT CHECK_HUESPED_ESTADO_REGISTRO CHECK ( ESTADO_REGISTRO IN ( 'ACTIVO',
                                                                         'ELIMINADO' ) )
);

CREATE TABLE HABITACIONES (
   ID_HABITACION     NUMBER GENERATED BY DEFAULT AS IDENTITY,
   NUMERO            NUMBER NOT NULL,
   TIPO              VARCHAR2(50) NOT NULL,
   PRECIO            DECIMAL(10,2) NOT NULL,
   CAPACIDAD         NUMBER NOT NULL,
   ESTADO_HABITACION VARCHAR2(15) DEFAULT 'DISPONIBLE' NOT NULL,
   ESTADO_REGISTRO   VARCHAR2(15) DEFAULT 'ACTIVO' NOT NULL,
   CONSTRAINT PK_ID_HABITACION PRIMARY KEY ( ID_HABITACION ),
   CONSTRAINT CHK_NUMERO CHECK ( NUMERO > 0 ),
   CONSTRAINT CHK_TIPO
      CHECK ( TIPO IN ( 'SENCILLA',
                        'DOBLE',
                        'SUITE',
                        'ESTANDAR',
                        'DE LUJO' ) ),
   CONSTRAINT CHK_PRECIO CHECK ( PRECIO > 0 ),
   CONSTRAINT CHK_CAPACIDAD CHECK ( CAPACIDAD > 0 ),
   CONSTRAINT CHK_ESTADO_HABITACION
      CHECK ( ESTADO_HABITACION IN ( 'DISPONIBLE',
                                     'OCUPADA',
                                     'LIMPIEZA',
                                     'MANTENIMIENTO' ) ),
   CONSTRAINT CHK_ESTADO_REGISTRO CHECK ( ESTADO_REGISTRO IN ( 'ACTIVO',
                                                               'ELIMINADO' ) )
);

CREATE TABLE RESERVAS (
   ID_RESERVA      NUMBER GENERATED BY DEFAULT AS IDENTITY,
   ID_HUESPED      NUMBER NOT NULL,
   ID_HABITACION   NUMBER NOT NULL,
   FECHA_ENTRADA   DATE NOT NULL,
   FECHA_SALIDA    DATE NOT NULL,
   ESTADO_RESERVA  VARCHAR2(15) DEFAULT 'CONFIRMADA' NOT NULL,
   ESTADO_REGISTRO VARCHAR2(15) DEFAULT 'ACTIVO' NOT NULL,
   CONSTRAINT PK_ID_RESERVA PRIMARY KEY ( ID_RESERVA ),
   CONSTRAINT CHK_FECHAS CHECK ( FECHA_ENTRADA < FECHA_SALIDA ),
   CONSTRAINT CHK_ESTADO_RESERVA
      CHECK ( ESTADO_RESERVA IN ( 'CONFIRMADA',
                                  'EN_CURSO',
                                  'FINALIZADA',
                                  'CANCELADA' ) ),
   CONSTRAINT CHK_RES_ESTADO_REGISTRO CHECK ( ESTADO_REGISTRO IN ( 'ACTIVO',
                                                                   'ELIMINADO' ) )
);