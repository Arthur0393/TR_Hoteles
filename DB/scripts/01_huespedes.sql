GRANT CONNECT, RESOURCE TO HUESPEDES;
ALTER SESSION SET CURRENT_SCHEMA = HUESPEDES;
DECLARE
   v_count NUMBER;
BEGIN
   SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'HUESPEDES';
   IF v_count = 0 THEN
      EXECUTE IMMEDIATE 'CREATE TABLE HUESPEDES (
   ID_HUESPED        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
   NOMBRE            VARCHAR2(50) NOT NULL,
   APELLIDO_PATERNO  VARCHAR2(50) NOT NULL,
   APELLIDO_MATERNO  VARCHAR2(50) NOT NULL,
   EMAIL             VARCHAR2(100) NOT NULL,
   TELEFONO          VARCHAR2(10) NOT NULL,
   DOCUMENTO         VARCHAR2(30) NOT NULL,
   NACIONALIDAD      VARCHAR2(30) NOT NULL,
   ESTADO_REGISTRO   VARCHAR2(30) NOT NULL,
   CONSTRAINT PK_ID_HUESPED PRIMARY KEY ( ID_HUESPED ),
   CONSTRAINT CHECK_DOCUMENTO
      CHECK ( DOCUMENTO IN ( ''CREDENCIAL'',
                             ''PASAPORTE'',
                             ''CARTILLA_MILITAR'',
                             ''CURP'' ) ),
   CONSTRAINT HUESPED_TELEFONO_CHK CHECK ( REGEXP_LIKE ( TELEFONO,
                                                         ''^[0-9]{10}$'' ) ),
   CONSTRAINT CHECK_HUESPED_ESTADO_REGISTRO CHECK ( ESTADO_REGISTRO IN ( ''ACTIVO'',
                                                                         ''ELIMINADO'' ) )
)';
   END IF;
END;
