ALTER SESSION SET CONTAINER = FREEPDB1;

BEGIN
   EXECUTE IMMEDIATE 'CREATE TABLESPACE USERS DATAFILE ''/opt/oracle/oradata/FREE/FREEPDB1/users01.dbf'' SIZE 100M AUTOEXTEND ON NEXT 10M';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
BEGIN
   EXECUTE IMMEDIATE 'CREATE USER HABITACIONES IDENTIFIED BY "habitaciones" QUOTA UNLIMITED ON USERS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
GRANT CONNECT, RESOURCE TO HABITACIONES;
ALTER SESSION SET CURRENT_SCHEMA = HABITACIONES;

DECLARE
   v_count NUMBER;
BEGIN
   SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'HABITACIONES';
   IF v_count = 0 THEN
      EXECUTE IMMEDIATE 'CREATE TABLE HABITACIONES (
   ID_HABITACION     NUMBER GENERATED BY DEFAULT AS IDENTITY,
   NUMERO            NUMBER NOT NULL,
   TIPO              VARCHAR2(50) NOT NULL,
   PRECIO            DECIMAL(10,2) NOT NULL,
   CAPACIDAD         NUMBER NOT NULL,
   ESTADO_HABITACION VARCHAR2(15) DEFAULT ''DISPONIBLE'' NOT NULL,
   ESTADO_REGISTRO   VARCHAR2(15) DEFAULT ''ACTIVO'' NOT NULL,
   CONSTRAINT PK_ID_HABITACION PRIMARY KEY ( ID_HABITACION ),
   CONSTRAINT CHK_NUMERO CHECK ( NUMERO > 0 ),
   CONSTRAINT CHK_TIPO
      CHECK ( TIPO IN ( ''SENCILLA'',
                        ''DOBLE'',
                        ''SUITE'',
                        ''ESTANDAR'',
                        ''DE LUJO'' ) ),
   CONSTRAINT CHK_PRECIO CHECK ( PRECIO > 0 ),
   CONSTRAINT CHK_CAPACIDAD CHECK ( CAPACIDAD > 0 ),
   CONSTRAINT CHK_ESTADO_HABITACION
      CHECK ( ESTADO_HABITACION IN ( ''DISPONIBLE'',
                                     ''OCUPADA'',
                                     ''LIMPIEZA'',
                                     ''MANTENIMIENTO'' ) ),
   CONSTRAINT CHK_ESTADO_REGISTRO CHECK ( ESTADO_REGISTRO IN ( ''ACTIVO'',
                                                               ''ELIMINADO'' ) )
)';
   END IF;
END;
/
