BEGIN
   EXECUTE IMMEDIATE 'CREATE TABLESPACE USERS DATAFILE ''/opt/oracle/oradata/FREE/FREEPDB1/users01.dbf'' SIZE 100M AUTOEXTEND ON NEXT 10M';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
BEGIN
   EXECUTE IMMEDIATE 'CREATE USER RESERVAS IDENTIFIED BY "reservas" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
GRANT CONNECT, RESOURCE TO RESERVAS;
ALTER SESSION SET CURRENT_SCHEMA = RESERVAS;

DECLARE
   v_count NUMBER;
BEGIN
   SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'RESERVAS';
   IF v_count = 0 THEN
      EXECUTE IMMEDIATE 'CREATE TABLE RESERVAS (
   ID_RESERVA      NUMBER GENERATED BY DEFAULT AS IDENTITY,
   ID_HUESPED      NUMBER NOT NULL,
   ID_HABITACION   NUMBER NOT NULL,
   FECHA_ENTRADA   DATE NOT NULL,
   FECHA_SALIDA    DATE NOT NULL,
   ESTADO_RESERVA  VARCHAR2(15) DEFAULT ''CONFIRMADA'' NOT NULL,
   ESTADO_REGISTRO VARCHAR2(15) DEFAULT ''ACTIVO'' NOT NULL,
   CONSTRAINT PK_ID_RESERVA PRIMARY KEY ( ID_RESERVA ),
   CONSTRAINT CHK_FECHAS CHECK ( FECHA_ENTRADA < FECHA_SALIDA ),
   CONSTRAINT CHK_ESTADO_RESERVA
      CHECK ( ESTADO_RESERVA IN ( ''CONFIRMADA'',
                                  ''EN_CURSO'',
                                  ''FINALIZADA'',
                                  ''CANCELADA'' ) ),
   CONSTRAINT CHK_RES_ESTADO_REGISTRO CHECK ( ESTADO_REGISTRO IN ( ''ACTIVO'',
                                                                   ''ELIMINADO'' ) )
)';
   END IF;
END;
